name = "Ravi"
age = 20

# Using format()
print("Using format(): My name is {} and I am {} years old.".format(name, age))

# Using f-strings
print(f"Using f-string: My name is {name} and I am {age} years old.")

# Using % operator
print("Using %% operator: My name is %s and I am %d years old." % (name, age))
