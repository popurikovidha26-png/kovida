# Creating two sets
set1 = {10, 20, 30, 40, 50}
set2 = {30, 40, 50, 60, 70}

print("Set 1:", set1)
print("Set 2:", set2)

# Union operation
print("Union:", set1.union(set2))

# Intersection operation
print("Intersection:", set1.intersection(set2))

# Difference operation
print("Difference:", set1.difference(set2))
