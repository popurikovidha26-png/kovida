# Creating a list
my_list = [30, 10, 50, 20, 40]

print("Original List:", my_list)

# Append operation
my_list.append(60)
print("After Append:", my_list)

# Insert operation
my_list.insert(2, 25)
print("After Insert:", my_list)

# Remove operation
my_list.remove(10)
print("After Remove:", my_list)

# Sort operation
my_list.sort()
print("After Sort:", my_list)

# Reverse operation
my_list.reverse()
print("After Reverse:", my_list)
